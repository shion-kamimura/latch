export function getHelp(): string {
  return [
    'Latch',
    '',
    'Evidence-based verification for AI-generated code.',
    '',
    'Usage: latch [options]',
    '       latch verify [options]',
    '       latch plan [options]',
    '',
    'Options:',
    '  -h, --help     Show this help message',
    '  -v, --version  Show the CLI version',
    '',
    'Verify options:',
    '  --base <ref>                Compare with a branch, tag, or commit',
    '  --issue-file <path>         Read requirements from a local Markdown file',
    '  --include-untracked <path>  Include one explicitly named untracked file',
    '  --json                      Print the resolved inputs as JSON',
    '',
    'Plan options:',
    '  --profile <path>            Read the user-managed BYOK permission profile',
    '                              outside the worktree (or set LATCH_PROFILE)',
    '  --base <ref>                Compare with a branch, tag, or commit',
    '  --issue-file <path>         Read requirements from a local Markdown file',
    '  --include-untracked <path>  Include one explicitly named untracked file',
    '  --json                      Print the requirement plan as JSON',
    '',
    'The verify command resolves inputs only. The plan command extracts',
    'requirements and proposes missing scenarios without executing tests or',
    'target code. Neither command reports verification success.',
    '',
  ].join('\n');
}
